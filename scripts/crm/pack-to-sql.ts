// Turns a pack definition file into a migration that publishes it.
//
//   deno run --allow-read --allow-write scripts/crm/pack-to-sql.ts \
//     packs/trading_institute/v1.json
//
// Writes supabase/migrations/<timestamp>_crm_pack_<key>_v<n>.sql. The file is
// validated first; a published version must never be edited, so publish a
// new version instead (the migration fails if the same version exists with a
// different checksum).
import { type PackDefinition, validatePack } from "./pack.ts";

async function sha256(text: string): Promise<string> {
  const digest = await crypto.subtle.digest(
    "SHA-256",
    new TextEncoder().encode(text),
  );
  return [...new Uint8Array(digest)]
    .map((b) => b.toString(16).padStart(2, "0"))
    .join("");
}

function quote(text: string): string {
  return `'${text.replaceAll("'", "''")}'`;
}

function timestamp(): string {
  return new Date().toISOString().replace(/\D/g, "").slice(0, 14);
}

export async function packToSql(source: string): Promise<{
  pack: PackDefinition;
  sql: string;
}> {
  const pack = JSON.parse(source) as PackDefinition;
  const errors = validatePack(pack);
  if (errors.length) {
    throw new Error(`invalid pack:\n- ${errors.join("\n- ")}`);
  }

  const checksum = await sha256(source);
  const definition = JSON.stringify(pack);
  // Dollar-quote tag that cannot appear in the JSON.
  const tag = "$pack_" + checksum.slice(0, 8) + "$";

  const sql = `-- Publishes vertical pack ${pack.key} v${pack.version}.
-- Generated by scripts/crm/pack-to-sql.ts from packs/${pack.key}/v${pack.version}.json
-- (sha256 ${checksum}). Do not edit; publish a new version instead.

insert into crm.vertical_packs (key, name, description, is_default)
values (${quote(pack.key)}, ${quote(pack.name)}, ${
    quote(pack.description ?? "")
  }, ${pack.is_default ? "true" : "false"})
on conflict (key) do update
  set name = excluded.name,
      description = excluded.description;

do $guard$
begin
  if exists (
    select 1 from crm.pack_versions
    where pack_key = ${quote(pack.key)}
      and version = ${pack.version}
      and checksum <> ${quote(checksum)}
  ) then
    raise exception 'pack ${pack.key} v${pack.version} is already published with different content';
  end if;
end;
$guard$;

insert into crm.pack_versions (pack_key, version, definition, checksum)
values (${
    quote(pack.key)
  }, ${pack.version}, ${tag}${definition}${tag}::jsonb, ${quote(checksum)})
on conflict (pack_key, version) do nothing;
`;

  return { pack, sql };
}

if (import.meta.main) {
  const path = Deno.args[0];
  if (!path) {
    console.error("usage: pack-to-sql.ts <packs/<key>/v<n>.json>");
    Deno.exit(1);
  }

  const { pack, sql } = await packToSql(await Deno.readTextFile(path));
  const out =
    `supabase/migrations/${timestamp()}_crm_pack_${pack.key}_v${pack.version}.sql`;
  await Deno.writeTextFile(out, sql);
  console.log(`wrote ${out}`);
}
